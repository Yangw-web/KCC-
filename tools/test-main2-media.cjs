const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { spawnSync } = require('node:child_process');
const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'main2.html'), 'utf8');
for (const match of html.matchAll(/(?:src|href)="\.\/([^"#]+)(?:#[^"]*)?"/g)) assert.ok(fs.existsSync(path.join(root, match[1])), match[1]);
assert.ok(html.includes('src="./assets/main2-1020-web.mp4" type="video/mp4"'));
assert.ok(html.includes('autoplay muted loop playsinline'));
for (let n = 1; n <= 6; n++) assert.equal(html.split('src="./assets/main2_fixed_' + n + '.jpg"').length - 1, 1);
assert.ok(html.includes('src="./assets/main2-n-th-1.png"'), 'Keep the original first NEWS thumbnail');
const videoPath = path.join(root, 'assets/main2-1020-web.mp4');
const ffmpeg = path.join(root, 'tools/video-dependencies/imageio_ffmpeg/binaries/ffmpeg-win-x86_64-v7.1.exe');
const result = spawnSync(ffmpeg, ['-v', 'error', '-i', videoPath, '-f', 'null', '-'], { encoding: 'utf8', windowsHide: true });
assert.equal(result.status, 0, result.stderr);
console.log('PASS: all page assets, six replacement thumbnails, unchanged first NEWS image, autoplay/loop settings and full video decode.');
